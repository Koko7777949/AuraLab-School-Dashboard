const translations: Record<'ar' | 'en' | 'fr', Translations> = { ar, en, fr };

export type Locale = 'ar' | 'en' | 'fr';
export const LOCALES: { code: Locale; label: string; dir: 'rtl' | 'ltr' }[] = [
  { code: 'ar', label: 'العربية', dir: 'rtl' },
  { code: 'en', label: 'English', dir: 'ltr' },
  { code: 'fr', label: 'Français', dir: 'ltr' },
];

export function localeDir(locale: Locale): 'rtl' | 'ltr' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

/**
 * Get a translated string by key.
 * Defaults to Arabic if the language or key is not found.
 */
export function t(key: TranslationKey, lang: Locale = 'ar'): string {
  return translations[lang]?.[key] ?? translations.ar[key] ?? key;
}

export type { TranslationKey, Translations };
